#: The generated top is FINN's own, not either Kernel's.
WRAPPER_MODULE = "finn.dataflow.mvau.decomposed_wrapper"

#: The wrapper's control signals, and which of the two clocks is primary.
#:
#: One authority, because two stages need it and they must not disagree.  The
#: constraints generator names both clocks and states that the doubled one is
#: *derived* -- half the period, never chosen separately -- and IP packaging
#: has to say which clock the streams are synchronous to.  Answering that
#: separately in each place would be two statements of one fact, and the one
#: that reached the tool would win.
PRIMARY_CLOCK = "ap_clk"
DOUBLED_CLOCK = "ap_clk2x"
RESET_SIGNAL = "ap_rst_n"

_COMPOSITION_PATH = QualifiedPath("hardware.mvau.composition")


def _fail(code: str, message: str) -> MVAUElaborationError:
    return MVAUElaborationError(
        (Finding(FindingKind.LIMITATION, code, _COMPOSITION_PATH, message),)
    )


def _literal(value: object) -> str:
    return str(int(value)) if isinstance(value, bool) else str(value)


def _parameter_list(values: Mapping[str, object]) -> str:
    return ",\n        ".join(f".{name}({_literal(values[name])})" for name in sorted(values))


def _byte_aligned(bits: int) -> int:
    return ((bits + 7) // 8) * 8


def render_decomposed_wrapper(
    module_name: str,
    replay: Mapping[str, object],
    compute: Mapping[str, object],
    *,
    activation_bits: int,
    weight_bits: int,
    output_bits: int,
) -> str:
    """The generated top: a replay buffer feeding a dot product.

    Wired exactly as ``mvu_vvu_axi`` wires its internal replay -- the replay's
    ``olast`` becomes the dot product's ``s_axis_input_tlast``, and ``ofin`` is
    left unconnected because the fused core never reads it either.  That
    correspondence is what fixture 5 checks, and it is why this generator and
    that fixture must be the same code.
    """

    return f"""// Generated by finn.dataflow.mvau.decomposed_provider -- do not edit.
// The decomposed MVAU: finn replay_buffer -> finnlib dotp_axi.
module {module_name} #(
    parameter WSTREAM = {_byte_aligned(weight_bits)},
    parameter ISTREAM = {_byte_aligned(activation_bits)},
    parameter OSTREAM = {_byte_aligned(output_bits)}
)(
    input  logic ap_clk,
    input  logic ap_clk2x,
    input  logic ap_rst_n,
    input  logic [WSTREAM-1:0] in1_V_tdata,
    input  logic in1_V_tvalid,
    output logic in1_V_tready,
    input  logic [ISTREAM-1:0] in0_V_tdata,
    input  logic in0_V_tvalid,
    output logic in0_V_tready,
    output logic [OSTREAM-1:0] out0_V_tdata,
    output logic out0_V_tvalid,
    input  logic out0_V_tready
);
    localparam int unsigned REPLAY_W = {_literal(replay["W"])};

    uwire rst = !ap_rst_n;
    uwire [REPLAY_W-1:0] replayed_tdata;
    uwire replayed_tvalid;
    uwire replayed_tlast;
    uwire replayed_tready;

    replay_buffer #(
        {_parameter_list(replay)}
    ) activation_replay (
        .clk(ap_clk), .rst(rst),
        .idat(in0_V_tdata[REPLAY_W-1:0]),
        .ivld(in0_V_tvalid),
        .irdy(in0_V_tready),
        .odat(replayed_tdata),
        .olast(replayed_tlast),
        .ofin(),
        .ovld(replayed_tvalid),
        .ordy(replayed_tready)
    );

    dotp_axi #(
        {_parameter_list(compute)}
    ) dot_product (
        .ap_clk(ap_clk), .ap_clk2x(ap_clk2x), .ap_rst_n(ap_rst_n),
        .s_axis_weights_tdata(in1_V_tdata),
        .s_axis_weights_tvalid(in1_V_tvalid),
        .s_axis_weights_tready(in1_V_tready),
        .s_axis_input_tdata(replayed_tdata),
        .s_axis_input_tvalid(replayed_tvalid),
        .s_axis_input_tlast(replayed_tlast),
        .s_axis_input_tready(replayed_tready),
        .m_axis_output_tdata(out0_V_tdata),
        .m_axis_output_tvalid(out0_V_tvalid),
        .m_axis_output_tready(out0_V_tready)
    );
endmodule
"""


#: The ports the generated top and its stitching shim both carry, in order.
#:
#: One list, used to declare the shim and to wire the core, so the two cannot
#: drift apart.  ``(name, direction, width parameter or None)``.
_WRAPPER_PORTS: tuple[tuple[str, str, str | None], ...] = (
    ("ap_clk", "input", None),
    ("ap_clk2x", "input", None),
    ("ap_rst_n", "input", None),
    ("in1_V_tdata", "input", "WSTREAM"),
    ("in1_V_tvalid", "input", None),
    ("in1_V_tready", "output", None),
    ("in0_V_tdata", "input", "ISTREAM"),
    ("in0_V_tvalid", "input", None),
    ("in0_V_tready", "output", None),
    ("out0_V_tdata", "output", "OSTREAM"),
    ("out0_V_tvalid", "output", None),
    ("out0_V_tready", "input", None),
)


def render_stitch_shim(
    module_name: str,
    *,
    activation_bits: int,
    weight_bits: int,
    output_bits: int,
) -> str:
    """A plain-Verilog top that instantiates the generated SystemVerilog one.

    Not decoration, and not a style preference.  ``create_bd_cell -type module
    -reference`` **refuses a SystemVerilog top file** -- Vivado answers
    ``[filemgmt 56-195] ... This type is not allowed as the top file in the
    reference`` -- so the generated ``.sv`` top cannot be placed in a block
    design at all.  ``-type hier -reference`` is not the alternative it looks
    like: Vivado reports ``[BD 41-1695] Specified '-reference' ... will be
    ignored while creating 'hier' cell``, so it silently makes an empty
    hierarchy.

    A ``.v`` shim over the same ports is what works, and it is exactly what
    baseline FINN does -- ``matrixvectoractivation_rtl`` stages
    ``{gen_top_module}_wrapper.v`` for the same reason.  With it, Vivado also
    infers ``in0_V``, ``in1_V`` and ``out0_V`` as AXI-Stream bus interfaces
    from the signal naming, so the unit stitches as streams rather than as
    loose pins.

    Verilog-2001 only: no ``logic``, no ``uwire``, no ``.*``.  The generated
    top keeps every SystemVerilog construct it needs, and this reaches it
    through explicit connections, so the RTL fixture 5 validates is untouched.
    """

    widths = {"WSTREAM": weight_bits, "ISTREAM": activation_bits, "OSTREAM": output_bits}
    declarations = ",\n    ".join(
        f"{direction} wire {f'[{parameter}-1:0] ' if parameter else ''}{name}"
        for name, direction, parameter in _WRAPPER_PORTS
    )
    connections = ",\n        ".join(f".{name}({name})" for name, _, _ in _WRAPPER_PORTS)
    parameters = ",\n    ".join(
        f"parameter {name} = {_byte_aligned(bits)}" for name, bits in widths.items()
    )
    overrides = ", ".join(f".{name}({name})" for name in widths)
    return f"""// Generated by finn.dataflow.mvau.decomposed_provider -- do not edit.
// Plain-Verilog stitching top: create_bd_cell cannot reference a .sv top file.
module {module_name}_wrapper #(
    {parameters}
)(
    {declarations}
);
    {module_name} #({overrides}) core (
        {connections}
    );
endmodule
"""


