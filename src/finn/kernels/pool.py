"""Max pooling over FinnLib's HLS ``pooling_stream``: the first HLS kernel.

``pooling_stream`` (FinnLib ``hls/nonlin/pooling.hpp``) is a reduction alone: it
takes the maximum of the beats it is given until one arrives with ``last``, and
then presents it. It does not walk a feature map: the window is the channel's.
The kernel's input port reads an ``(H, W, C)`` tensor, or one at the
graph's rank, ``(1, H, W, C)`` (each leading axis one, read at ``ZERO``), through the
window, ``(oh * SH + kh, ow * SW + kw, c)``, on the schedule ``(oh, ow, c, kh, kw)``
with ``c`` folded by PE, and closes each window with the marker of its innermost
two indices (``closes``), so the channel's adapter (``input_gen``) presents the
windows in order and its loop-end marker becomes the stream's TLAST, as dotp's
activation TLAST closes each reduction. Its output, the tensor it states
(``output_tensor``), is ``(oh, ow, c)`` at the input's rank (``(1, oh, ow, c)``),
presented after each window (``reduces``), PE
channels a beat, in the input's element: the maximum of values in a range stays in
it.

The module is an HLS top that FINN writes from the point's values (``pool_top``,
an ``HlsSource``): ``hls::vector`` lanes of the element's ``ap_int``/``ap_uint``,
glue from the AXIS beat and its TLAST to ``pooling_stream``'s ``flit_t`` and from
its results to the output beat, lane zero lowest, and ``pooling_stream`` with an
elementwise ``std::max``. It runs on ``ap_clk`` and ``ap_rst_n``; its AXIS pins are
spelled as HLS spells them (``s_axis_TDATA``). Its period is the platform's.

Its domain is what that hardware takes: ordinary integers (``max`` over
``ap_int``/``ap_uint``), any window and stride its channel can present, any PE
dividing the channels. Its resources are not characterised: it states so
(``kernel-resources``). Its computation's reference is test-side until a KernelOp
reaches it: ``tests/support/kernel_specs/pool.py``.
"""

from __future__ import annotations

from typing import ClassVar

from finn.core.space import (
    Decision,
    Param,
    Rejected,
    constraint,
    derived,
    divisors_of,
    reject,
    view,
)
from finn.dataflow.datatypes import QONNXDataType
from finn.dataflow.gemm import ZERO
from finn.dataflow.schedule import Access, Affine, Index, Schedule
from finn.dataflow.tensor import Tensor
from finn.kernels.artifacts.abi import Clocking, Endpoint
from finn.kernels.artifacts.contributions import Contribution, CopiedSource, HlsSource
from finn.kernels.artifacts.hls import axis_type
from finn.kernels.base import Kernel, extent_of
from finn.kernels.laws import Axis, AxisSpelling
from finn.kernels.library import ModuleSpec
from finn.kernels.port import axis
from finn.kernels.port_model import IndexedPort, ScheduledPort
from finn.kernels.values.domains import Integer
from finn.platform.capabilities import Platform, Resources

oh, ow, c, kh, kw = (Index(name) for name in ("oh", "ow", "c", "kh", "kw"))

#: The FinnLib headers ``pool_top`` includes, and the ones they include.
HEADERS = tuple(
    CopiedSource("finnlib", path)
    for path in ("hls/nonlin/pooling.hpp", "hls/util/util.hpp", "hls/shape/input_gen.hpp")
)
#: Every submodule named after its top, so that two configurations share a netlist; no
#: deadlock detector, which is simulation-only logic.
DIRECTIVES = ("config_rtl -module_auto_prefix", "config_rtl -deadlock_detection none")
#: The elements its top takes: ordinary integers, as ``ap_int``/``ap_uint`` lanes.
ELEMENTS = Integer()


def element_type(dtype: QONNXDataType) -> str:
    """The C++ type of an ordinary integer element: ``ap_int<b>`` or ``ap_uint<b>``."""
    return f"{'ap_int' if dtype.signed() else 'ap_uint'}<{dtype.bitwidth()}>"


def pool_top(name: str, element: QONNXDataType, pe: int, input_bits: int, output_bits: int) -> str:
    """The text of the HLS top ``name``: ``pooling_stream`` taking the maximum of each
    window of PE ``element`` lanes, from an AXIS input of ``input_bits`` with TLAST
    closing each window to an AXIS output of ``output_bits``, lanes low first."""
    bits = element.bitwidth()
    return f"""// Generated by finn.kernels.pool -- do not edit.
#include <ap_axi_sdata.h>
#include <ap_int.h>
#include <hls_stream.h>
#include <hls_vector.h>
#include "pooling.hpp"
#include "util.hpp"

using Element = {element_type(element)};
using Lanes = hls::vector<Element, {pe}>;
using InBeat = {axis_type(input_bits, True)};
using OutBeat = {axis_type(output_bits, False)};

// An input beat as pooling_stream's flit: its lanes, low first, and its TLAST.
void from_axis(hls::stream<InBeat> &src, hls::stream<flit_t<Lanes>> &dst) {{
#pragma HLS pipeline II=1 style=flp
	if(!src.empty()) {{
		InBeat const  beat = src.read();
		Lanes  lanes;
		for(unsigned  i = 0; i < {pe}; i++) {{
#pragma HLS unroll
			lanes[i] = Element(ap_uint<{bits}>(beat.data.range({bits}*i + {bits - 1}, {bits}*i)));
		}}
		dst.write(flit_t<Lanes>(beat.last, lanes));
	}}
}}

// A result as an output beat: its lanes, low first, its padding zero.
void to_axis(hls::stream<Lanes> &src, hls::stream<OutBeat> &dst) {{
#pragma HLS pipeline II=1 style=flp
	if(!src.empty()) {{
		Lanes const  lanes = src.read();
		OutBeat  beat = 0;
		for(unsigned  i = 0; i < {pe}; i++) {{
#pragma HLS unroll
			ap_uint<{bits}> const  lane = lanes[i].range({bits - 1}, 0);
			beat.range({bits}*i + {bits - 1}, {bits}*i) = lane;
		}}
		dst.write(beat);
	}}
}}

void {name}(hls::stream<InBeat> &s_axis, hls::stream<OutBeat> &m_axis) {{
#pragma HLS interface axis port=s_axis
#pragma HLS interface axis port=m_axis
#pragma HLS interface ap_ctrl_none port=return
#pragma HLS dataflow disable_start_propagation

	// Internal FIFOs, as FinnLib's own tops decouple their AXI streams.
	static hls::stream<flit_t<Lanes>>  src0;
	static hls::stream<Lanes>  dst0;
#pragma HLS stream variable=src0 depth=2
#pragma HLS stream variable=dst0 depth=2

	from_axis(s_axis, src0);
	pooling_stream(src0, dst0, [](Lanes const &a, Lanes const &b) {{
#pragma HLS inline
		Lanes  y;
		for(unsigned  i = 0; i < {pe}; i++) {{
#pragma HLS unroll
			y[i] = std::max(a[i], b[i]);
		}}
		return  y;
	}});
	to_axis(dst0, m_axis);
}}
"""


#: The stem of its HLS top: the module is ``finn_pool_<key16>``.
STEM = "finn_pool"


class PoolKernel(Kernel):
    """Max pooling of each ``window`` at ``stride`` (rows, columns) of an HWC tensor;
    see the module docstring."""

    id = "finnlib.pooling_stream"

    window: tuple[int, int] = Param()
    stride: tuple[int, int] = Param()
    platform: Platform = Param()
    # The tensor its input port reads: a fact it is given.
    input_tensor: Tensor = Param()

    @constraint
    def geometry_supported(self) -> bool | Rejected:
        for name, pair in (("window", self.window), ("stride", self.stride)):
            if len(pair) != 2 or any(type(value) is not int or value < 1 for value in pair):
                return reject("pool-geometry", f"a {name} is two positive integers, not {pair}")
        return True

    @derived
    def extents(self) -> dict[Index, int] | Rejected:
        """The window's extents are its own, and the windows' from the input: as many as
        fit whole, ``(H - KH) // SH + 1`` a row (no padding: a pad is its own stage). The
        channels are bound from the input's tensor."""
        (rows, columns), (row_step, column_step) = self.window, self.stride
        shape = self.input_tensor.shape
        if (
            len(shape) < 3
            or any(extent != 1 for extent in shape[:-3])
            or shape[-3] < rows
            or shape[-2] < columns
        ):
            return reject(
                "pool-geometry", f"a {rows}x{columns} window fits no (..., H, W, C) image {shape}"
            )
        windows = {
            oh: (shape[-3] - rows) // row_step + 1,
            ow: (shape[-2] - columns) // column_step + 1,
        }
        return self._bound({kh: rows, kw: columns, **windows})

    channels = extent_of(c)
    pe: int = Decision(domain=divisors_of(channels))

    @derived
    def leading(self) -> tuple[Affine, ...]:
        """An index for each of the input's leading axes, one image each: ``ZERO``."""
        return (ZERO,) * (len(self.input_tensor.shape) - 3)

    @derived
    def input_index(self) -> tuple[Affine, ...]:
        rows, columns = self.stride
        return (*self.leading, oh * rows + kh, ow * columns + kw, Affine.of(c))

    @derived
    def output_index(self) -> tuple[Index | Affine, ...]:
        return (*self.leading, oh, ow, c)

    @derived
    def schedule(self) -> Schedule | Rejected:
        """Window by window, PE channels a beat, the window's positions innermost."""
        return self.bound_schedule(order=(oh, ow, c, kh, kw), factors={c: self.pe})

    def _accesses(self) -> list[Access]:
        found: list[Access] = []
        if self.input.binds:
            found.append(self.input.access)
        return found

    @derived
    def port_clocking(self) -> Clocking:
        return type(self).clock_domain

    input = IndexedPort(
        label="input",
        transport=Axis(bus="s_axis", spelling=AxisSpelling.UPPER),
        clocking=port_clocking,
        endpoint=Endpoint.TARGET,
        tensor=input_tensor,
        admits=ELEMENTS,
        schedule=schedule,
        index=input_index,
        lanes=(c,),
        closes=(kh, kw),
    )

    @view
    def element_dtype(self) -> QONNXDataType:
        """The input's element: a window's maximum is one of its values."""
        return self.input.element.dtype

    @derived
    def output_tensor(self) -> Tensor | Rejected:
        """Its output: ``(OH, OW, C)`` at the input's rank, in the input's element."""
        shape = self.spanned(self.output_index)
        if isinstance(shape, Rejected):
            return shape
        return Tensor(shape, self.input.element)

    output = ScheduledPort(
        label="output",
        transport=Axis(bus="m_axis", spelling=AxisSpelling.UPPER),
        clocking=port_clocking,
        endpoint=Endpoint.INITIATOR,
        tensor=output_tensor,
        admits=ELEMENTS,
        schedule=schedule,
        index=output_index,
        lanes=(c,),
        reduces=(kh, kw),
    )

    @constraint
    def element_supported(self) -> bool | Rejected:
        """An ordinary integer: ``std::max`` over ``ap_int`` or ``ap_uint`` lanes."""
        return ELEMENTS.check(self.input_tensor.element.dtype)

    @view
    def resource_use(self) -> Resources | Rejected:
        return reject("kernel-resources", "the pooling module's resources are not characterised")

    @view
    def parameters(self) -> dict[str, int | str]:
        """None: the HLS top is written from the point's values."""
        return {}

    @view
    def module_sources(self) -> tuple[Contribution, ...] | Rejected:
        """Its HLS request, written from the point's values: checked to provide the
        module when it is built."""
        element, pe = self.element_dtype, self.pe
        input_axis = axis(self.input.physical_spec(idle=False), self.input.stream)
        if isinstance(input_axis, Rejected):
            return input_axis
        output_axis = axis(self.output.physical_spec(idle=False), self.output.stream)
        if isinstance(output_axis, Rejected):
            return output_axis
        input_bits, output_bits = input_axis.carrier_bits, output_axis.carrier_bits
        return (
            HlsSource.request(
                STEM,
                lambda name: pool_top(name, element, pe, input_bits, output_bits),
                HEADERS,
                self.platform.period_ns,
                DIRECTIVES,
            ),
        )

    module_spec: ClassVar[ModuleSpec] = ModuleSpec(STEM)

    @view
    def cycles(self) -> int | Rejected:
        beats: list[int] = []
        if self.input.placed:
            beats.append(self.input.stream.sequence.form.beats)
        if self.output.placed:
            beats.append(self.output.stream.sequence.form.beats)
        return (
            max(beats)
            if beats
            else reject(
                "kernel-cycles", f"no port of {type(self).__qualname__} carries a stream's beats"
            )
        )


__all__ = ["DIRECTIVES", "HEADERS", "PoolKernel", "STEM", "element_type"]
