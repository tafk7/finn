"""Softmax over the last axis, on FinnLib's HLS ``SoftMax``.

``SoftMax`` (FinnLib ``hls/nonlin/softmax.hpp``) normalizes each row of ``N`` elements,
SIMD a beat, in three stages: the row's maximum; ``exp(x - max)`` in binary32, each
rounded to a fixed point of 24 fraction bits and summed there; each exponential divided
by the sum in binary32. Rows follow one another without a gap. A row whose maximum is
infinite shares one evenly among its infinite elements, the others zero; a NaN leaves
its row undefined.

The kernel's input port reads a tensor of any rank, row-major, the last axis (``c``)
folded by SIMD; its output, the tensor it states (``output_tensor``), has the input's
shape in FLOAT32 and is presented on the same schedule. The hardware presents a row
only after reading it whole: that lag is latency, which no port states. Its cycles are
the exponentiation stage's, which spends a cycle a row taking the row's maximum
(``frame_cycles``).

The module is an HLS top that FINN writes from the point's values (``softmax_top``, an
``HlsSource``): the input beat's lanes, lane zero lowest, as the core's element (an
integer's ``ap_int``/``ap_uint``, a binary32's bits as a ``float``), ``SoftMax<TI, float,
N, SIMD>``, and each result's bits into the output beat. It runs on ``ap_clk`` and
``ap_rst_n``, with no control bus; its AXIS pins are spelled as HLS spells them
(``s_axis_TDATA``). Its period is the platform's.

Its domain is what that hardware takes: a FLOAT32 input, or an ordinary integer of at
most 32 bits (FinnLib's own sweep's widths), converted to binary32 before the maximum
is subtracted (exactly up to 24 bits); any SIMD dividing the last axis. Its results
approximate the function: their range is FLOAT32's own, as nothing here bounds them to
[0, 1]. Its resources are not characterised: it states so (``kernel-resources``). Its
computation's reference is test-side until a KernelOp reaches it:
``tests/kernels/specs/softmax.py``.
"""

from __future__ import annotations

from finn.core.space import (
    ConstraintGroup,
    Decision,
    Param,
    Rejected,
    constraint,
    derived,
    divisors_of,
    reject,
)
from finn.dataflow.datatypes import QONNXDataType, resolve_qonnx_datatype_name
from finn.dataflow.schedule import Index, Schedule
from finn.dataflow.tensor import Tensor
from finn.kernels.artifacts.abi import Endpoint
from finn.kernels.artifacts.contributions import Contribution, CopiedSource, HlsSource
from finn.kernels.artifacts.hls import axis_type
from finn.kernels.base import LeafKernel, extent_of, interface
from finn.kernels.pool import DIRECTIVES, element_type
from finn.kernels.port import AxiStreamPort
from finn.kernels.transport import AxisSpelling
from finn.kernels.utilization import RESOURCES_SEMANTICS
from finn.kernels.values.domains import Integer, admit_element
from finn.kernels.values.semantics import QONNX_DATATYPE_VALUE_SEMANTICS
from finn.platform.capabilities import Platform, Resources

c = Index("c")

#: The FinnLib headers ``softmax_top`` includes, and the ones they include.
HEADERS = tuple(
    CopiedSource("finnlib", path) for path in ("hls/nonlin/softmax.hpp", "hls/util/util.hpp")
)
FLOAT32 = resolve_qonnx_datatype_name("FLOAT32")
#: The integers its top takes, as ``ap_int``/``ap_uint`` lanes: FinnLib's tested widths.
INTEGERS = Integer(1, 32)


def lane_type(dtype: QONNXDataType) -> str:
    """The C++ type of an input lane: ``float`` for FLOAT32, else the integer's."""
    return "float" if dtype.name == FLOAT32.name else element_type(dtype)


def softmax_top(
    name: str, element: QONNXDataType, n: int, simd: int, input_bits: int, output_bits: int
) -> str:
    """The text of the HLS top ``name``: ``SoftMax`` over rows of ``n`` ``element``
    values, ``simd`` lanes a beat, from an AXIS input of ``input_bits`` to an AXIS output
    of ``output_bits`` carrying binary32 lanes, lanes low first."""
    if element.name == FLOAT32.name:
        read = """Binary32  lane;
			lane.i = ap_uint<32>(beat.range(32*i + 31, 32*i)).to_uint();
			lanes[i] = lane.f;"""
    else:
        bits = element.bitwidth()
        read = f"lanes[i] = Element(ap_uint<{bits}>(beat.range({bits}*i + {bits - 1}, {bits}*i)));"
    return f"""// Generated by finn.kernels.softmax -- do not edit.
#include <ap_int.h>
#include <cstdint>
#include <hls_stream.h>
#include <hls_vector.h>
#include "softmax.hpp"

using Element = {lane_type(element)};
using Lanes = hls::vector<Element, {simd}>;
using Results = hls::vector<float, {simd}>;
using InBeat = {axis_type(input_bits, False)};
using OutBeat = {axis_type(output_bits, False)};

// A binary32 and its bits: HLS reads a union as a bit cast.
union Binary32 {{
	float  f;
	uint32_t  i;
}};

// An input beat as its lanes, low first.
void from_axis(hls::stream<InBeat> &src, hls::stream<Lanes> &dst) {{
#pragma HLS pipeline II=1 style=flp
	if(!src.empty()) {{
		InBeat const  beat = src.read();
		Lanes  lanes;
		for(unsigned  i = 0; i < {simd}; i++) {{
#pragma HLS unroll
			{read}
		}}
		dst.write(lanes);
	}}
}}

// The results as an output beat: each lane's binary32 bits, low first.
void to_axis(hls::stream<Results> &src, hls::stream<OutBeat> &dst) {{
#pragma HLS pipeline II=1 style=flp
	if(!src.empty()) {{
		Results const  lanes = src.read();
		OutBeat  beat = 0;
		for(unsigned  i = 0; i < {simd}; i++) {{
#pragma HLS unroll
			Binary32  lane;
			lane.f = lanes[i];
			beat.range(32*i + 31, 32*i) = lane.i;
		}}
		dst.write(beat);
	}}
}}

void {name}(hls::stream<InBeat> &s_axis, hls::stream<OutBeat> &m_axis) {{
#pragma HLS interface axis port=s_axis
#pragma HLS interface axis port=m_axis
#pragma HLS interface ap_ctrl_none port=return
#pragma HLS dataflow disable_start_propagation

	// Internal FIFOs, as FinnLib's own tops decouple their AXI streams.
	static hls::stream<Lanes>  src0;
	static hls::stream<Results>  dst0;
#pragma HLS stream variable=src0 depth=2
#pragma HLS stream variable=dst0 depth=2
	static SoftMax<Element, float, {n}, {simd}>  core;

	from_axis(s_axis, src0);
	core.execute(src0, dst0);
	to_axis(dst0, m_axis);
}}
"""


class SoftmaxKernel(LeafKernel):
    """Softmax over the last axis of its input; see the module docstring."""

    id = "finnlib.softmax"
    version = 1
    # The stem of its HLS top: the module is ``finn_softmax_<key16>``.
    rtl_module = "finn_softmax"

    platform: Platform = Param()
    # The tensor its input port reads: a fact it is given.
    input_tensor: Tensor = Param(required=False)

    @derived
    def indices(self) -> tuple[Index, ...]:
        """The input's axes, ``c`` (a row's elements) innermost; the output keeps them."""
        rank = len(self.input_tensor.shape)
        return (*(Index(f"a{axis}") for axis in range(rank - 1)), c)

    row = extent_of(c)  # N, the elements a row
    # SIMD elements of a row a beat.
    simd: int = Decision(domain=divisors_of(row))

    @derived
    def schedule(self) -> Schedule | Rejected:
        """Row-major over the input's axes, ``c`` split by SIMD innermost."""
        return self.bound_schedule(self.indices, {c: self.simd})

    input = AxiStreamPort(
        name="s_axis",
        endpoint=Endpoint.TARGET,
        tensor=input_tensor,
        schedule=schedule,
        index=indices,
        lanes=(c,),
        spelling=AxisSpelling.UPPER,
    )

    @derived(semantics=QONNX_DATATYPE_VALUE_SEMANTICS)
    def input_dtype(self) -> QONNXDataType:
        """The input's element type: its tensor's."""
        return self.input.element.dtype

    @derived
    def output_tensor(self) -> Tensor | Rejected:
        """Its results: the input's shape, in FLOAT32 over its whole range."""
        shape = self.spanned(self.indices)
        if isinstance(shape, Rejected):
            return shape
        element = admit_element(FLOAT32, None)
        if isinstance(element, Rejected):
            return element
        return Tensor(shape, element)

    output = AxiStreamPort(
        name="m_axis",
        endpoint=Endpoint.INITIATOR,
        tensor=output_tensor,
        schedule=schedule,
        index=indices,
        lanes=(c,),
        spelling=AxisSpelling.UPPER,
    )
    input_end = interface("input")
    output_end = interface("output")

    @constraint
    def element_supported(self) -> bool | Rejected:
        """FLOAT32, or an ordinary integer of at most 32 bits."""
        dtype = self.input_tensor.element.dtype
        return True if dtype.name == FLOAT32.name else INTEGERS.check(dtype)

    admission = ConstraintGroup(element_supported)

    @derived
    def frame_cycles(self) -> int | Rejected:
        """The clock cycles a frame takes: the exponentiation stage's, a beat a cycle and
        one cycle a row more, in which it takes the row's maximum
        (``softmax.hpp``'s ``exponentiate``)."""
        schedule = self.schedule
        if isinstance(schedule, Rejected):
            return schedule
        beats = schedule.beat_count
        return beats + beats * self.simd // self.row

    @derived(semantics=RESOURCES_SEMANTICS)
    def resource_use(self) -> Resources | Rejected:
        return reject("kernel-resources", "the softmax module's resources are not characterised")

    @derived
    def parameters(self) -> dict[str, int | str]:
        """None: the HLS top is written from the point's values."""
        return {}

    @derived
    def sources(self) -> tuple[Contribution, ...]:
        element, n, simd = self.input_dtype, self.row, self.simd
        input_bits, output_bits = self.input.axis.carrier_bits, self.output.axis.carrier_bits
        return (
            HlsSource.request(
                type(self).rtl_module,
                lambda name: softmax_top(name, element, n, simd, input_bits, output_bits),
                HEADERS,
                self.platform.period_ns,
                DIRECTIVES,
            ),
        )


__all__ = ["FLOAT32", "HEADERS", "INTEGERS", "SoftmaxKernel", "lane_type", "softmax_top"]
