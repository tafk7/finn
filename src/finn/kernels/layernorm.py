"""Normalization over the last axis, on FinnLib's HLS ``layernorm``.

``layernorm`` (FinnLib ``hls/nonlin/layernorm.hpp``) normalizes each row of ``N``
elements, SIMD a beat, to ``(x - mean) / sqrt(var + epsilon)``, without a scale or a
bias, in three stages: the row's mean; each element less the mean, and the mean of
their squares (the variance); ``1 / sqrt(var + epsilon)`` and its product with each
centred element. Its statistics are binary32: each stage adds a beat's lanes as a tree
and accumulates the beats in order, then divides by ``N``. A row's statistic must reach
the next stage before that stage reads the row, and the buffer between two stages holds
one row.

The kernel's input port reads a tensor of any rank, row-major, the last axis (``c``)
folded by SIMD; its output, the tensor it states (``output_tensor``), has the input's
shape in FLOAT32 and is presented on the same schedule. The hardware presents a row
only after reading it whole: that lag is latency, which no port states. Its cycles are
stated as a beat a cycle, the least a frame takes (``LeafKernel``'s): the core's
accumulations in binary32 and its stages' wait for each row's statistic may make it
slower, by an amount its HLS schedule decides, which nothing here states yet.

The module is an HLS top that FINN writes from the point's values (``layernorm_top``, an
``HlsSource``): the input beat's binary32 lanes, lane zero lowest, as ``float``s,
``layernorm<N>`` with ``epsilon`` as a binary32 constant, and each result's bits into
the output beat. It runs on ``ap_clk`` and ``ap_rst_n``, with no control bus; its AXIS
pins are spelled as HLS spells them (``s_axis_TDATA``). Its period is the platform's.

Its domain is what that hardware takes: a FLOAT32 input (the mean stage adds a beat's
lanes in the input's own type, so integer lanes would overflow), any SIMD dividing the
last axis. ``epsilon`` describes the computation: a supplied fact, rounded to binary32
(the top's constant), and refused unless finite. Its results approximate the function:
their range is FLOAT32's own. A row whose deviations' squares exceed binary32 has an
infinite variance, and results of zero or NaN. Its resources are not characterised: it
states so (``kernel-resources``). Its computation's reference is test-side until a
KernelOp reaches it: ``tests/kernels/specs/layernorm.py``.
"""

from __future__ import annotations

import math
import struct

from finn.core.space import (
    ConstraintGroup,
    Decision,
    Param,
    Rejected,
    constraint,
    derived,
    divisors_of,
    reject,
)
from finn.dataflow.datatypes import resolve_qonnx_datatype_name
from finn.dataflow.schedule import Index, Schedule
from finn.dataflow.tensor import Tensor
from finn.kernels.artifacts.abi import Endpoint
from finn.kernels.artifacts.contributions import Contribution, CopiedSource, HlsSource
from finn.kernels.artifacts.hls import axis_type
from finn.kernels.base import LeafKernel, extent_of, interface
from finn.kernels.pool import DIRECTIVES
from finn.kernels.port import AxiStreamPort
from finn.kernels.transport import AxisSpelling
from finn.kernels.utilization import RESOURCES_SEMANTICS
from finn.kernels.values.domains import admit_element
from finn.platform.capabilities import Platform, Resources

c = Index("c")

#: The FinnLib headers ``layernorm_top`` includes, and the ones they include.
HEADERS = tuple(
    CopiedSource("finnlib", path) for path in ("hls/nonlin/layernorm.hpp", "hls/util/util.hpp")
)
FLOAT32 = resolve_qonnx_datatype_name("FLOAT32")


def binary32(value: float) -> float | Rejected:
    """``value`` rounded to binary32, or a ``layernorm-epsilon`` refusal unless finite."""
    try:
        rounded = float(struct.unpack("!f", struct.pack("!f", value))[0])
    except (OverflowError, struct.error) as error:
        return reject("layernorm-epsilon", f"epsilon {value!r} is no binary32: {error}")
    if not math.isfinite(rounded):
        return reject("layernorm-epsilon", f"epsilon must be finite binary32, not {value!r}")
    return rounded


def float_literal(value: float) -> str:
    """A C++ ``float`` literal of ``value``, a binary32 value: its shortest decimal as a
    double (``1e-05f``, ``0.25f``), which rounds back to it as a ``float``."""
    return f"{value!r}f"


def layernorm_top(
    name: str, n: int, simd: int, epsilon: float, input_bits: int, output_bits: int
) -> str:
    """The text of the HLS top ``name``: ``layernorm`` over rows of ``n`` binary32 values,
    ``simd`` lanes a beat, with ``epsilon`` (a binary32 value), from an AXIS input of
    ``input_bits`` to an AXIS output of ``output_bits``, lanes low first."""
    return f"""// Generated by finn.kernels.layernorm -- do not edit.
#include <ap_int.h>
#include <cstdint>
#include <hls_stream.h>
#include <hls_vector.h>
#include "layernorm.hpp"

using Lanes = hls::vector<float, {simd}>;
using InBeat = {axis_type(input_bits, False)};
using OutBeat = {axis_type(output_bits, False)};

// A binary32 and its bits: HLS reads a union as a bit cast.
union Binary32 {{
	float  f;
	uint32_t  i;
}};

// An input beat as its lanes, low first.
void from_axis(hls::stream<InBeat> &src, hls::stream<Lanes> &dst) {{
#pragma HLS pipeline II=1 style=flp
	if(!src.empty()) {{
		InBeat const  beat = src.read();
		Lanes  lanes;
		for(unsigned  i = 0; i < {simd}; i++) {{
#pragma HLS unroll
			Binary32  lane;
			lane.i = ap_uint<32>(beat.range(32*i + 31, 32*i)).to_uint();
			lanes[i] = lane.f;
		}}
		dst.write(lanes);
	}}
}}

// The results as an output beat: each lane's binary32 bits, low first.
void to_axis(hls::stream<Lanes> &src, hls::stream<OutBeat> &dst) {{
#pragma HLS pipeline II=1 style=flp
	if(!src.empty()) {{
		Lanes const  lanes = src.read();
		OutBeat  beat = 0;
		for(unsigned  i = 0; i < {simd}; i++) {{
#pragma HLS unroll
			Binary32  lane;
			lane.f = lanes[i];
			beat.range(32*i + 31, 32*i) = lane.i;
		}}
		dst.write(beat);
	}}
}}

void {name}(hls::stream<InBeat> &s_axis, hls::stream<OutBeat> &m_axis) {{
#pragma HLS interface axis port=s_axis
#pragma HLS interface axis port=m_axis
#pragma HLS interface ap_ctrl_none port=return
#pragma HLS dataflow disable_start_propagation

	// Internal FIFOs, as FinnLib's own tops decouple their AXI streams.
	static hls::stream<Lanes>  src0;
	static hls::stream<Lanes>  dst0;
#pragma HLS stream variable=src0 depth=2
#pragma HLS stream variable=dst0 depth=2

	from_axis(s_axis, src0);
	layernorm<{n}>(src0, dst0, {float_literal(epsilon)});
	to_axis(dst0, m_axis);
}}
"""


class LayerNormKernel(LeafKernel):
    """Normalization over the last axis of its input; see the module docstring."""

    id = "finnlib.layernorm"
    version = 1
    # The stem of its HLS top: the module is ``finn_layernorm_<key16>``.
    rtl_module = "finn_layernorm"

    platform: Platform = Param()
    # The tensor its input port reads: a fact it is given.
    input_tensor: Tensor = Param(required=False)
    # Added to the variance before its square root: a fact of the computation.
    epsilon: float = Param()

    @derived
    def indices(self) -> tuple[Index, ...]:
        """The input's axes, ``c`` (a row's elements) innermost; the output keeps them."""
        rank = len(self.input_tensor.shape)
        return (*(Index(f"a{axis}") for axis in range(rank - 1)), c)

    row = extent_of(c)  # N, the elements a row
    # SIMD elements of a row a beat.
    simd: int = Decision(domain=divisors_of(row))

    @derived
    def schedule(self) -> Schedule | Rejected:
        """Row-major over the input's axes, ``c`` split by SIMD innermost."""
        return self.bound_schedule(self.indices, {c: self.simd})

    input = AxiStreamPort(
        name="s_axis",
        endpoint=Endpoint.TARGET,
        tensor=input_tensor,
        schedule=schedule,
        index=indices,
        lanes=(c,),
        spelling=AxisSpelling.UPPER,
    )

    @derived
    def output_tensor(self) -> Tensor | Rejected:
        """Its results: the input's shape, in FLOAT32 over its whole range."""
        shape = self.spanned(self.indices)
        if isinstance(shape, Rejected):
            return shape
        element = admit_element(FLOAT32, None)
        if isinstance(element, Rejected):
            return element
        return Tensor(shape, element)

    output = AxiStreamPort(
        name="m_axis",
        endpoint=Endpoint.INITIATOR,
        tensor=output_tensor,
        schedule=schedule,
        index=indices,
        lanes=(c,),
        spelling=AxisSpelling.UPPER,
    )
    input_end = interface("input")
    output_end = interface("output")

    @derived
    def native_epsilon(self) -> float | Rejected:
        """``epsilon`` as the top's constant: rounded to binary32, refused unless finite."""
        return binary32(self.epsilon)

    @constraint
    def element_supported(self) -> bool | Rejected:
        """FLOAT32 only: the mean stage adds a beat's lanes in their own type."""
        dtype = self.input_tensor.element.dtype
        if dtype.name == FLOAT32.name:
            return True
        return reject(
            "dtype-family",
            f"{dtype.name}: the layernorm core takes FLOAT32 only; its mean stage adds a "
            "beat's lanes in the input's own type, which overflows an integer",
            values={"datatype": dtype.name, "expected": FLOAT32.name},
        )

    @constraint
    def epsilon_supported(self) -> bool | Rejected:
        """``epsilon`` is a finite binary32 value."""
        found = self.native_epsilon
        return found if isinstance(found, Rejected) else True

    admission = ConstraintGroup(element_supported, epsilon_supported)

    @derived(semantics=RESOURCES_SEMANTICS)
    def resource_use(self) -> Resources | Rejected:
        return reject("kernel-resources", "the layernorm module's resources are not characterised")

    @derived
    def parameters(self) -> dict[str, int | str]:
        """None: the HLS top is written from the point's values."""
        return {}

    @derived
    def sources(self) -> tuple[Contribution, ...] | Rejected:
        epsilon = self.native_epsilon
        if isinstance(epsilon, Rejected):
            return epsilon
        n, simd = self.row, self.simd
        input_bits, output_bits = self.input.axis.carrier_bits, self.output.axis.carrier_bits
        return (
            HlsSource.request(
                type(self).rtl_module,
                lambda name: layernorm_top(name, n, simd, epsilon, input_bits, output_bits),
                HEADERS,
                self.platform.period_ns,
                DIRECTIVES,
            ),
        )


__all__ = ["FLOAT32", "HEADERS", "LayerNormKernel", "binary32", "float_literal", "layernorm_top"]
