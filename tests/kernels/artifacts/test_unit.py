def test_two_buses_are_the_decoder_s_slaves_each_at_its_offset() -> None:
    """The decoder's slave port is the unit's, each master its bus's, its address
    truncated to the bus's bits; every other pin of the core is the unit's."""
    assert unit(5, 6).text("unit") == TWO


def test_the_unit_s_pins_are_the_core_s_its_buses_one_port() -> None:
    """The core's pins in order, its AXI-Lite targets replaced by ``s_axi_control`` where
    the first was, its address the unit's window's bits; the decoder's port takes every
    member, the protections among them."""
    found = unit(5, 6, 5)
    names = [pin.name for pin in found.abi.pins]
    assert names == ["ap_clk", "ap_rst_n", "s_axis_0", "m_axis_0", CONTROL]
    widths = {member.logical: member.width for member in found.port.signals}
    assert widths == {**MEMBERS, "awaddr": 12, "araddr": 12, "awprot": 3, "arprot": 3}


def test_three_buses_are_placed_as_the_map_says_the_protections_where_a_bus_takes_them() -> None:
    text = unit(5, 6, 5, protections=True).text("unit")
    assert ".BASE({12'h80, 12'h40, 12'h0})," in text
    assert ".SIZE({8'd5, 8'd6, 8'd5})" in text
    assert ".s_axilite_2_AWPROT(m_awprot)," in text
    assert "s_axilite_0_AWPROT" not in text
    assert ".s_axilite_2_RDATA(m_rdata[2])," in text


def test_one_bus_is_the_unit_s_port_renamed_and_no_decoder() -> None:
    """One bus is the port, its members as the bus has them, its address truncated to the
    bus's bits; no decoder is instantiated, and none is a file of the unit."""
    found = unit(6)
    text = found.text("unit")
    assert "axilite_decoder" not in text
    assert ".s_axilite_0_AWADDR(s_axi_control_AWADDR[5:0])," in text
    assert ".s_axilite_0_WDATA(s_axi_control_WDATA)," in text
    assert {member.logical for member in found.port.signals} == set(MEMBERS)


def test_the_unit_is_named_as_its_content(tmp_path: Path) -> None:
    """One content, one name: the text, the decoder's bytes and the core's IP, its own name
    left out; another map, core, decoder or IP is another name. Its files are the decoder,
    read from its root, and its module; one bus has its module alone."""
    found = unit(5, 6)
    assert found.name(b"decoder") == unit(5, 6).name(b"decoder")
    others = {
        found.name(b"other decoder"),
        CoreUnit(CORE, SUBCORE, found.core_abi, (0, 128), 4096).name(b"decoder"),
        CoreUnit(CORE.replace("0", "1"), SUBCORE, found.core_abi, (0, 64), 4096).name(b"decoder"),
        CoreUnit(CORE, f"vendor:library:{CORE}:2.8", found.core_abi, (0, 64), 4096).name(
            b"decoder"
        ),
    }
    assert found.name(b"decoder") not in others and len(others) == 4
    decoder = tmp_path / "finnlib" / DECODER_SOURCE.path
    decoder.parent.mkdir(parents=True)
    decoder.write_bytes(b"decoder")
    emitted = emit_unit(found, tmp_path / "unit", roots={"finnlib": tmp_path / "finnlib"})
    name = found.name(b"decoder")
    assert (emitted.entry_point, emitted.sources) == (name, (DECODER_SOURCE.path, f"{name}.sv"))
    assert (emitted.directory / f"{name}.sv").read_text() == found.text(name)
    alone = emit_unit(unit(6), tmp_path / "alone", roots={})
    assert alone.sources == (f"{alone.entry_point}.sv",)


def test_the_unit_s_files_are_written_as_a_module_s(tmp_path: Path) -> None:
    """Under its directory resolved once, never through a link: a destination whose decoder
    directory is a link is refused before anything is written."""
    root = tmp_path / "finnlib"
    (root / DECODER_SOURCE.path).parent.mkdir(parents=True)
    (root / DECODER_SOURCE.path).write_bytes(b"decoder")
    (tmp_path / "elsewhere").mkdir()
    out = tmp_path / "unit"
    out.mkdir()
    (out / DECODER_SOURCE.path.split("/")[0]).symlink_to(
        tmp_path / "elsewhere", target_is_directory=True
    )
    with pytest.raises(BuildError, match="is a link"):
        emit_unit(unit(5, 6), out, roots={"finnlib": root})
    assert not any((tmp_path / "elsewhere").iterdir())
    assert sorted(path.name for path in out.iterdir()) == [DECODER_SOURCE.path.split("/")[0]]


def test_the_unit_is_packaged_at_its_window(tmp_path: Path) -> None:
    """The unit's one register block is its window, the grouper's, whatever it is: at a
    least window of 128 bytes, two 64-byte buses take 128, which its placement assigns."""
    found = CoreUnit(CORE, SUBCORE, core_abi(axilite("a", 6), axilite("b", 6)), (0, 64), 128)
    decoder = tmp_path / "finnlib" / DECODER_SOURCE.path
    decoder.parent.mkdir(parents=True)
    decoder.write_bytes(b"decoder")
    emitted = emit_unit(found, tmp_path / "unit", roots={"finnlib": tmp_path / "finnlib"})
    script = package_tcl(
        emitted,
        found.abi.pins,
        part="xczu3eg-sbva484-1-e",
        clock_ns=5.0,
        display_name="unit",
        run_synth=False,
    )
    assert "set_property range 128 $block" in script.splitlines()


@pytest.mark.parametrize(
    ("bus", "reason"),
    [
        (axilite("s_axilite", 6, data=64), "s_axilite: wdata of 64 bits, not 32; rdata of 64"),
        (
            Bus("cfg", StandardProtocol.AXILITE, (Member("awaddr", "cfg_awaddr", 6),)),
            "cfg has no awvalid, awready, wdata",
        ),
        (stream("s_axis_0", Endpoint.TARGET), "s_axis_0 is no AXI-Lite target"),
    ],
    ids=["wide", "members", "stream"],
)
def test_a_bus_the_unit_cannot_wire_says_why(bus: Bus, reason: str) -> None:
    assert (unsupported(bus) or "").startswith(reason)
    assert unsupported(axilite("s_axilite", 6, protections=True)) is None


@pytest.mark.parametrize(
    ("bits", "offsets", "message"),
    [
        ((), (), "presents no AXI-Lite bus"),
        ((5, 6), (0,), "1 offsets for its 2 AXI-Lite buses"),
        ((5, 6), (0, 32), "64 bytes at 0x20 is not aligned"),
        ((5, 6), (0, 4096), "64 bytes at 0x1000 is not aligned to itself within"),
        ((6, 6), (-64, 0), "64 bytes at -0x40 is not aligned to itself within"),
        ((6, 6), (0, 0), "s_axilite_0 and s_axilite_1 overlap at 0x0"),
        ((5, 6), (0, 0), "s_axilite_0 and s_axilite_1 overlap at 0x0"),
        ((6,), (64,), "one bus is the unit's port, at 0, not 0x40"),
    ],
    ids=["no-bus", "short-map", "misaligned", "outside", "negative", "same", "inside", "one"],
)
def test_a_unit_that_cannot_be_made_is_refused(
    bits: tuple[int, ...], offsets: tuple[int, ...], message: str
) -> None:
    buses = (axilite(f"s_axilite_{index}", each) for index, each in enumerate(bits))
    with pytest.raises(BuildError, match=message):
        CoreUnit(CORE, SUBCORE, core_abi(*buses), offsets, 4096)
