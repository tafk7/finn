CORE = "finn_dataflowcore_0123456789abcdef"
#: The core's IP as its packaging states it: its VLNV, of a vendor, library and version
#: of its own.
SUBCORE = f"vendor:library:{CORE}:2.7"


def axilite(port: str, bits: int, *, protections: bool = False, data: int = 32) -> Bus:
    """A core's AXI-Lite target ``port`` of ``bits`` address bits, as its top presents it."""
    widths: dict[str, int | None] = {
        **MEMBERS,
        "awaddr": bits,
        "araddr": bits,
        "wdata": data,
        "rdata": data,
    }
    if protections:
        widths.update(awprot=3, arprot=3)
    members = (Member(name, name, width or bits) for name, width in widths.items())
    return top_bus(Bus(port, StandardProtocol.AXILITE, members), port, CLOCK, RESET)


def stream(port: str, endpoint: Endpoint) -> Bus:
    """A core's 8-bit AXI-Stream ``port``."""
    members = (
        Member(name, f"{port}_{name.upper()}", 8 if name == "tdata" else 1)
        for name in ("tdata", "tvalid", "tready")
    )
    return Bus(port, StandardProtocol.AXIS, members, endpoint, associated_clock=CLOCK)


def core_abi(*buses: Bus) -> Abi:
    """A core's pins: its clock and reset, one stream in and one out, and ``buses``."""
    return Abi(
        (
            *Clocking().signals(),
            stream("s_axis_0", Endpoint.TARGET),
            stream("m_axis_0", Endpoint.INITIATOR),
            *buses,
        )
    )


def unit(*bits: int, protections: bool = False) -> CoreUnit:
    """The unit of a core presenting a bus of each of ``bits`` address bits, placed as the
    grouper places them, in a window of 4 KiB."""
    buses = [axilite(f"s_axilite_{index}", each) for index, each in enumerate(bits)]
    if protections:
        buses[-1] = axilite(f"s_axilite_{len(bits) - 1}", bits[-1], protections=True)
    offsets = placed_windows([1 << each for each in bits], 0)
    return CoreUnit(CORE, SUBCORE, core_abi(*buses), offsets, 4096)


